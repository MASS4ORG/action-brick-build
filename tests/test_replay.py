import base64
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('replay', Path(__file__).parents[1] / 'scripts/replay.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


class ReplayTests(unittest.TestCase):
    def setup_archives(self, root, include_twin=True, available=True):
        receipts = []
        for variant in ['source'] + (['turian3.4'] if include_twin else []):
            filename = f'org.example.brick-1.0.0--{variant}.brick'
            payload = ('exact original ' + variant).encode()
            if available:
                (root / filename).write_bytes(payload)
            receipts.append({'packageId': 'org.example.brick', 'version': '1.0.0', 'variant': variant,
                             'file': filename, 'available': available,
                             'integrity': 'sha256-' + base64.b64encode(hashlib.sha256(payload).digest()).decode()})
        (root / 'recorded.json').write_text(json.dumps(receipts))
        return receipts

    def test_complete_recorded_release_skips_rebuild_and_replays_exact_bytes(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            output = root / 'out'
            output.mkdir()
            receipts = self.setup_archives(root)
            self.assertFalse(module.replay(root, output, True, '3.4.0', False))
            module.replay(root, output, True, '3.4.0', True)
            for receipt in receipts:
                self.assertEqual((root / receipt['file']).read_bytes(), (output / receipt['file']).read_bytes())

    def test_missing_twin_requires_build_and_original_source_overrides_rebuilt_source(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            output = root / 'out'
            output.mkdir()
            receipts = self.setup_archives(root, include_twin=False)
            self.assertTrue(module.replay(root, output, True, '3.4.0', False))
            (output / receipts[0]['file']).write_bytes(b'different regenerated bytes')
            module.replay(root, output, True, '3.4.0', True)
            self.assertEqual((root / receipts[0]['file']).read_bytes(), (output / receipts[0]['file']).read_bytes())

    def test_corrupted_replay_fails_before_using_it(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            receipts = self.setup_archives(root)
            (root / receipts[0]['file']).write_bytes(b'corrupt')
            with self.assertRaises(ValueError):
                module.replay(root, root, True, '3.4.0', False)

    def test_inaccessible_pending_archive_rebuild_must_match_recorded_hash(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            output = root / 'out'
            output.mkdir()
            receipts = self.setup_archives(root, include_twin=False, available=False)
            self.assertTrue(module.replay(root, output, False, '3.4.0', False))
            candidate = output / receipts[0]['file']
            candidate.write_bytes(b'wrong')
            with self.assertRaisesRegex(ValueError, 'rebuild differs'):
                module.replay(root, output, False, '3.4.0', True)
            candidate.write_bytes(b'exact original source')
            module.replay(root, output, False, '3.4.0', True)
